#!/usr/bin/env python3
"""Generate the local rootkit rule file from one table.

Keeping the table here instead of 40 hand-written blocks means the family list
is reviewable in one screen, every rule gets the same PE-and-name-and-technique
shape, and adding a family is one line.

Run with the service stopped: the generated file names malware families and the
APIs they use, which is exactly what the product's own AMSI provider is built to
block when it sees it in a script.
"""
import io

PATH = r"C:\Users\wensz\Downloads\wenle-av\rules\local\rootkits.avrule"

TECHNIQUES = {
    "rootkit": ["NtLoadDriver", "SeLoadDriverPrivilege", "IoCreateDevice",
                "ObRegisterCallbacks", "PhysicalDrive", "Harddisk0", "globalroot"],
    "bootkit": ["NtLoadDriver", "SeLoadDriverPrivilege", "PhysicalDrive",
                "Harddisk0", "IoCreateDevice"],
    "wiper": ["PhysicalDrive", "Harddisk0", "DeviceIoControl", "MBR"],
    "uefi": ["bootmgfw", "EFI", "Firmware", "SecureBoot", "PhysicalDrive"],
    "registry": ["mshta", "RunOnce", "powershell"],
    "trojan": ["PhysicalDrive"],
}

FAMILIES = [
    # Only names that were verified to occur inside a real sample. Every other
    # family name in this file's history was an analyst label -- the samples for
    # ZeroAccess, Duqu2, Carberp, Petya, Rustock, Shamoon and Sekoia contained
    # none of their own names. Those rules could only produce false positives on
    # files that mention the name (bcdboot.exe and vds.exe did), so they are
    # gone. Coverage for those families comes from the machine-code signatures.
    ("memz", "trojan", ["MEMZ"]),
]

HEADER = '''/*
 * Rootkit and bootkit families, local to this project.
 *
 * Generated by tools/gen_rootkit_rules.py -- edit the table there, not here.
 *
 * Each family rule requires three things together: a PE file
 * (`uint16(0) == 0x5A4D`), the family's own name, and at least one string the
 * family uses to install or hide itself. A document that mentions Rovnix, or a
 * source file that names these APIs, is not a PE and cannot match.
 *
 * Technique rules carry no family and a medium severity, so the trust layer
 * keeps a shipped driver reported rather than removed.
 */

'''

TRAILER = '''
rule rootkit_driver_load_technique {
    meta:
        description = "Technique: loading a driver from a user-mode image. Generic to the trust layer; a shipped driver does this too."
        severity = "medium"
        category = "rootkit"
    strings:
        $load = "NtLoadDriver" ascii wide
        $privilege = "SeLoadDriverPrivilege" ascii wide
        $device = "IoCreateDevice" ascii wide
        $callbacks = "ObRegisterCallbacks" ascii wide
    condition:
        uint16(0) == 0x5A4D and 2 of them
}

rule bootkit_disk_write_technique {
    meta:
        description = "Technique: opening a physical drive by name to write sectors. Disk tools do this; the trust layer keeps the signed ones reported, not removed."
        severity = "medium"
        category = "bootkit"
    strings:
        $drive = "PhysicalDrive0" ascii wide nocase
        $harddisk = "Harddisk0" ascii wide nocase
        $write = "WriteFile" ascii
    condition:
        uint16(0) == 0x5A4D and all of them
}

rule bootkit_uefi_esp_writer {
    meta:
        description = "Technique: writing into the EFI system partition from Windows. Firmware tools do this too."
        severity = "medium"
        category = "bootkit"
    strings:
        $esp = "EFI" ascii wide
        $loader = "bootmgfw" ascii wide nocase
        $write = "WriteFile" ascii
    condition:
        uint16(0) == 0x5A4D and all of them
}

rule rootkit_ssdt_tool {
    meta:
        description = "Technique: an image that carries the SSDT symbol used by hooking tools. Debuggers and EDR drivers do too."
        severity = "medium"
        category = "rootkit"
    strings:
        $ssdt = "KeServiceDescriptorTable" ascii wide
        $query = "ZwQuerySystemInformation" ascii wide
        $driver = "NtLoadDriver" ascii wide
    condition:
        uint16(0) == 0x5A4D and $ssdt and any of ($query, $driver)
}
'''


def block(rule_id, category, names, extras=()):
    prefix = category if category in ("bootkit", "wiper") else "rootkit"
    lines = [
        "rule %s_%s {" % (prefix, rule_id),
        "    meta:",
        '        description = "Family %s: its own name together with an install or hide string."' % names[0],
        '        severity = "high"',
        '        category = "%s"' % category,
        '        family = "%s"' % names[0],
        "    strings:",
    ]
    for index, name in enumerate(names, 1):
        lines.append('        $n%d = "%s" ascii wide nocase' % (index, name))
    techniques = list(TECHNIQUES[category]) + list(extras)
    for index, technique in enumerate(techniques, 1):
        lines.append('        $t%d = "%s" ascii wide' % (index, technique))
    lines += [
        "    condition:",
        "        uint16(0) == 0x5A4D and any of ($n*) and any of ($t*)",
        "}",
    ]
    return "\n".join(lines)


def main():
    blocks = [block(*entry) for entry in FAMILIES]
    text = HEADER + "\n\n".join(blocks) + "\n" + TRAILER
    with io.open(PATH, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    print("rules written:", len(blocks) + 4)


if __name__ == "__main__":
    main()
